// Scenario 33 - controlled demand → PO → GRN → financial invoice, with no duplicate stock.
import { scenario, assert, assertEq } from '../lib/harness.mjs'

await scenario('33-procurement', async (h) => {
  await h.createCompanyUI('Procurement Books')
  const features = await h.invoke('config:features:get')
  await h.invoke('config:features:set', { ...features, inventory: true })
  await h.page.reload()
  await h.page.waitForFunction(() => Boolean(window.total))
  const screen = await h.page.locator('[data-screen]').first().getAttribute('data-screen')
  if (screen === 'company-select') await h.openCompany('Procurement Books')
  else await h.waitScreen('gateway')
  const groups = await h.invoke('master:groups:list')
  const units = await h.invoke('master:units:list')
  const creditors = groups.find((group) => group.name === 'Sundry Creditors')
  const purchases = groups.find((group) => group.name === 'Purchase Accounts')
  const supplier = await h.invoke('master:ledgers:create', { name: 'Precision Components', groupId: creditors.id, openingBalance: 0, gstin: '27AAPFU0939F1ZV', stateCode: '27', address: 'Pune', taxType: null, gstRate: null, hsn: null })
  const purchaseLedger = await h.invoke('master:ledgers:create', { name: 'Raw Material Purchases', groupId: purchases.id, openingBalance: 0, gstin: null, stateCode: null, address: null, taxType: null, gstRate: 18, hsn: null })
  const item = await h.invoke('master:stockItems:create', { name: 'Machined Housing', groupId: null, unitId: units[0].id, hsn: '8483', gstRate: 18, cessRate: null, openingQtyMilli: 0, openingValue: 0, barcode: null, reorderLevelMilli: 10_000, valuationMethod: 'weighted_avg' })

  const req = await h.invoke('procurement:requisitionCreate', { date: '2026-08-24', neededBy: '2026-08-30', department: 'Assembly', note: 'August production lot', lines: [{ stockItemId: item.id, qtyMilli: 8_000, note: 'Rev B drawing' }] })
  await h.invoke('procurement:requisitionStatus', { id: req.id, status: 'submitted', note: null })
  await h.invoke('procurement:requisitionStatus', { id: req.id, status: 'approved', note: 'Within material budget' })
  const po = await h.invoke('procurement:orderCreate', { date: '2026-08-24', expectedDate: '2026-08-30', supplierLedgerId: supplier.id, requisitionId: req.id, note: 'Inspect dimensions on arrival', lines: [{ stockItemId: item.id, qtyMilli: 8_000, ratePaise: 25_000, gstRate: 18 }] })
  await h.invoke('procurement:orderStatus', { id: po.id, status: 'issued' })
  const receipt = await h.invoke('procurement:receiptCreate', { purchaseOrderId: po.id, date: '2026-08-24', note: 'One housing rejected at inspection', lines: [{ purchaseOrderLineId: po.lines[0].id, qtyReceivedMilli: 8_000, qtyAcceptedMilli: 7_000, qtyRejectedMilli: 1_000 }] })

  await h.goto('procurement')
  await h.page.getByText(req.number, { exact: true }).waitFor()
  await h.shot('00-procurement-control-tower')
  await h.page.getByRole('tab', { name: /Goods receipts/ }).click()
  await h.page.getByText(receipt.number, { exact: true }).waitFor()
  await h.shot('01-grn-traceability')

  await h.goto('voucher-entry')
  await h.click('tab-voucher-entry-purchase')
  await h.page.getByTestId('select-invoice-grn').selectOption(String(receipt.id))
  await h.page.getByTestId('picker-ledger').fill('Raw Material Purchases')
  await h.page.getByTestId('picker-ledger').press('Enter')
  await h.page.getByTestId('picker-ledger').press('Escape')
  await h.page.getByText('Exact match', { exact: true }).waitFor()
  assertEq(await h.page.getByTestId('picker-party').inputValue(), 'Precision Components', 'GRN prefills the PO supplier')
  assertEq(await h.page.locator('[data-testid="rows-invoice-lines"] input').nth(1).inputValue(), '7', 'GRN prefills accepted quantity')
  await h.shot('02-three-way-exact-match')
  await h.click('btn-save-voucher')
  await h.page.getByText(/saved —/, { exact: false }).last().waitFor()

  const stock = await h.invoke('report:stockSummary', { asOn: '2026-08-25' })
  assertEq(stock.find((row) => row.stockItemId === item.id).closingQtyMilli, 7_000, 'financial invoice does not receive the GRN stock twice')
  assertEq((await h.invoke('procurement:invoiceCandidates', { supplierLedgerId: supplier.id })).length, 0, 'matched GRN leaves the candidate queue')
  const vouchers = await h.invoke('voucher:list', { from: '2026-08-24', to: '2026-08-25' })
  assert(vouchers.some((voucher) => voucher.kind === 'purchase'), 'matched supplier invoice reaches the books')

  await h.goto('procurement')
  await h.page.getByRole('tab', { name: /Supplier intelligence/ }).click()
  await h.page.getByTestId('picker-supplier-comparison-item').fill('Machined Housing')
  await h.page.getByTestId('picker-supplier-comparison-item').press('Enter')
  await h.page.getByTestId(`supplier-comparison-${supplier.id}`).waitFor()
  await h.shot('03-supplier-intelligence')
  const history = await h.invoke('procurement:priceHistory', { stockItemIds: [item.id], supplierLedgerId: supplier.id })
  assertEq(history[0].ratePaise, 25_000, 'supplier rate memory reads the matched financial invoice')

  await h.page.getByRole('tab', { name: /Debit-note claims/ }).click()
  await h.page.getByText('Rejected quantity recorded', { exact: false }).waitFor()
  await h.shot('04-debit-note-claim')
  const [claim] = await h.invoke('procurement:debitNoteClaims')
  await h.click(`prepare-debit-note-${claim.sourceKey}`)
  await h.waitScreen('voucher-entry')
  await h.page.getByTestId('picker-ledger').fill('Raw Material Purchases')
  await h.page.getByTestId('picker-ledger').press('Enter')
  await h.page.evaluate(() => document.activeElement?.blur())
  await h.page.getByText('Linked procurement debit note:', { exact: false }).waitFor()
  await h.page.waitForFunction(() => !document.querySelector('[data-testid="btn-save-voucher"]')?.disabled)
  await h.shot('05-linked-debit-note-draft')
  await h.click('btn-save-voucher')
  await h.page.getByText(/saved —/, { exact: false }).last().waitFor()
  assertEq((await h.invoke('procurement:debitNoteClaims')).length, 0, 'posting closes the rejected-goods claim once')
  const stockAfterDebit = await h.invoke('report:stockSummary', { asOn: '2026-08-25' })
  assertEq(stockAfterDebit.find((row) => row.stockItemId === item.id).closingQtyMilli, 7_000, 'rejection debit note is financial-only because rejected stock never entered inventory')

  await h.goto('procurement')
  await h.page.getByRole('tab', { name: /^Reorder/ }).click()
  await h.page.getByTestId(`select-reorder-${item.id}`).check()
  await h.shot('06-reorder-suggestions')
  await h.click('create-reorder-orders')
  await h.page.getByRole('tab', { name: /Purchase orders/ }).waitFor()
  const ordersAfterReorder = await h.invoke('procurement:orders')
  assert(ordersAfterReorder.some((order) => order.status === 'draft' && order.note === 'Owner-approved reorder suggestions'), 'owner review creates an editable grouped PO draft')

  await h.page.getByRole('tab', { name: /^Vendors/ }).click()
  await h.click('onboard-vendor')
  await h.page.getByTestId('picker-vendor-ledger').fill('Precision Components')
  await h.page.getByTestId('picker-vendor-ledger').press('Enter')
  await h.fill('input-vendor-contact', 'Priya Menon')
  await h.fill('input-vendor-email', 'accounts@precision.example')
  await h.fill('input-vendor-account', '123456789012')
  await h.fill('input-vendor-ifsc', 'HDFC0001234')
  await h.click('save-vendor-profile')
  await h.page.getByText('Priya Menon', { exact: true }).waitFor()
  await h.click(`verify-vendor-${supplier.id}`)
  await h.page.getByText('verified', { exact: true }).waitFor()
  await h.shot('07-verified-vendor')
})
